# --- contact links ---------------------------------------------------------------------


def test_contact_values_become_links():
    html = render(
        emails=["wa@example.com"],
        phones=["+57 300 123 4567"],
        links=["github.com/wa", "https://wa.dev/x", "www.wa.dev"],
    )
    assert 'href="mailto:wa@example.com"' in html
    assert 'href="tel:+573001234567"' in html
    assert 'href="https://github.com/wa"' in html
    assert 'href="https://wa.dev/x"' in html
    assert 'href="https://www.wa.dev"' in html


def test_dangerous_links_are_shown_as_text_only():
    html = render(links=["javascript:alert(1)", "data:text/html,hi"])
    assert "javascript:alert(1)" in html
    assert 'href="javascript' not in html
    assert 'href="data' not in html


# --- escaping --------------------------------------------------------------------------


def test_text_from_the_resume_is_escaped():
    html = render(
        name="Ana <script>alert(1)</script> & Co",
        experience=["<img src=x onerror=alert(1)>"],
        education=["R&D <b>Lab</b>"],
    )
    assert "<script>alert" not in html
    assert "<img src=x" not in html
    assert "<b>Lab</b>" not in html
    assert "Ana &lt;script&gt;alert(1)&lt;/script&gt; &amp; Co" in html
    assert "R&amp;D &lt;b&gt;Lab&lt;/b&gt;" in html
    assert parse_html(html).balanced


def test_title_is_escaped_too():
    html = render(name="</title><script>x</script>")
    assert "<title>&lt;/title&gt;&lt;script&gt;x&lt;/script&gt; - ResumeLens</title>" in html


def test_page_is_self_contained():
    html = render(links=["https://wa.dev"])
    tags = {tag for tag, _ in parse_html(html).tags}
    assert not tags & {"script", "img", "iframe", "object", "link"}
    assert "@import" not in html and "src=" not in html


