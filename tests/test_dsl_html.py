ROOT = Path(__file__).resolve().parent.parent
VALID = sorted((ROOT / "examples" / "dsl" / "valid").glob("*.rl"))
VOID = {"meta", "br", "hr", "img", "input", "link"}


class Collector(HTMLParser):
    """Collects tags and text, and checks that tags are balanced."""

    def __init__(self):
        super().__init__()
        self.stack: list[str] = []
        self.tags: list[tuple[str, dict]] = []
        self.text: list[str] = []
        self.balanced = True

    def handle_starttag(self, tag, attrs):
        self.tags.append((tag, dict(attrs)))
        if tag not in VOID:
            self.stack.append(tag)

    def handle_endtag(self, tag):
        if not self.stack or self.stack.pop() != tag:
            self.balanced = False

    def handle_data(self, data):
        self.text.append(data)


def parse_html(html: str) -> Collector:
    collector = Collector()
    collector.feed(html)
    collector.close()
    return collector


def classes(page: Collector, name: str) -> list[str]:
    return [t for t, a in page.tags if name in (a.get("class") or "").split()]


def candidate(**changes) -> CandidateProfile:
    base = dict(
        name="Wednesday Addams",
        emails=[],
        phones=[],
        experience_years=3,
        education=[],
        skills=["JAVASCRIPT", "REACT", "NODE_JS", "POSTGRESQL", "GIT"],
        classifications={
            Profile.FULL_STACK_DEVELOPER: True,
            Profile.MACHINE_LEARNING_ENGINEER: False,
            Profile.BACKEND_DEVELOPER: False,
            Profile.DATA_SCIENTIST: False,
        },
    )
    base.update(changes)
    return CandidateProfile(**base)


def render(**changes) -> str:
    return render_html(validate(to_dsl_text(candidate(**changes))))


# --- the example profiles ---------------------------------------------------------


@pytest.mark.parametrize("path", VALID, ids=[p.stem for p in VALID])
def test_every_valid_example_renders_a_well_formed_page(path):
    html = render_html(validate(path.read_text(encoding="utf-8")))
    page = parse_html(html)
    assert page.balanced and page.stack == []
    assert html.startswith("<!DOCTYPE html>")
    assert '<html lang="en">' in html
    assert '<meta charset="UTF-8">' in html


@pytest.mark.parametrize("path", VALID, ids=[p.stem for p in VALID])
def test_page_shows_one_result_per_profile(path):
    page = parse_html(render_html(validate(path.read_text(encoding="utf-8"))))
    assert len(classes(page, "result")) == len(Profile)


def test_page_has_the_sections_of_the_assignment_example():
    text = " ".join(parse_html(render()).text)
    assert "Wednesday Addams" in text
    assert "Candidate profile generated by ResumeLens" in text
    assert "Normalized Technical Skills" in text
    assert "Qualification Evaluation" in text
    assert "Full Stack Developer" in text
    assert "ACCEPTED" in text


def test_skills_are_listed_in_order():
    text = [t.strip() for t in parse_html(render()).text if t.strip()]
    start = text.index("JAVASCRIPT")
    assert text[start : start + 5] == ["JAVASCRIPT", "REACT", "NODE_JS", "POSTGRESQL", "GIT"]


def test_each_skill_shows_its_category():
    page = parse_html(render())
    titles = [a["title"] for t, a in page.tags if "skill" in (a.get("class") or "").split()]
    assert titles == ["Language", "Frontend", "Backend", "Database", "Version Control"]


def test_accepted_and_rejected_profiles_are_marked():
    page = parse_html(render())
    assert len(classes(page, "accepted")) == 1
    assert len(classes(page, "rejected")) == 3
    text = " ".join(page.text)
    assert "Accepted profiles: Full Stack Developer" in text
    assert text.count("REJECTED") == 3


def test_summary_when_nothing_is_accepted():
    html = render(classifications={p: False for p in Profile})
    assert "No qualification pattern was satisfied." in html
    assert "Accepted profiles" not in html


def test_several_accepted_profiles_are_listed():
    html = render(
        classifications={
            Profile.FULL_STACK_DEVELOPER: True,
            Profile.MACHINE_LEARNING_ENGINEER: True,
        }
    )
    assert "Accepted profiles: Full Stack Developer, Machine Learning Engineer" in html


