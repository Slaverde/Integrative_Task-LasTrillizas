def run_cli(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "src.dsl", *args],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )


def test_command_line_renders_a_valid_profile(tmp_path):
    out = tmp_path / "wa.html"
    result = run_cli(str(ROOT / "examples/dsl/valid/wednesday_addams.rl"), str(out))
    assert result.returncode == 0
    assert "Wednesday Addams" in out.read_text(encoding="utf-8")


def test_command_line_rejects_an_invalid_profile(tmp_path):
    out = tmp_path / "bad.html"
    result = run_cli(str(ROOT / "examples/dsl/invalid/semantic_unknown_skill.rl"), str(out))
    assert result.returncode == 1
    assert "S1" in result.stderr
    assert not out.exists()


def test_command_line_without_arguments_prints_usage():
    result = run_cli()
    assert result.returncode == 2
    assert "usage" in result.stderr


